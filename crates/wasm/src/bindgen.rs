//! Generate JavaScript / TypeScript bindings for exported Certo functions.
//!
//! Only `pub fn` declarations with supported numeric types are included in
//! the typed interface.  Functions with Text/record parameters are still
//! exported but listed as `opaque` with a prose explanation.
//!
//! # Output
//!
//! For a module with:
//!
//! ```certo
//! pub fn add(a: Int, b: Int): Int = a + b
//! pub fn greet(name: Text): Text = name
//! ```
//!
//! `generate_dts()` emits:
//!
//! ```typescript
//! export interface CertoExports {
//!   add(a: bigint, b: bigint): bigint;
//!   // greet: Text params/return require manual memory management — see docs
//! }
//! export declare function load(path: string): Promise<CertoExports>;
//! ```
//!
//! `generate_js()` emits a small ESM loader.

use certo_ast::decl::{Decl, FnDecl};
use certo_ast::module::Module;
use certo_ast::types::TypeExpr;

// ------------------------------------------------------------------ //
// Public API
// ------------------------------------------------------------------ //

/// Generate a `.d.ts` TypeScript declaration file.
pub fn generate_dts(module: &Module, module_name: &str) -> String {
    let fns = collect_pub_fns(module);
    let mut out = String::new();

    out.push_str("// Generated by certo-wasm — do not edit\n");
    out.push_str(&format!("// Module: {}\n\n", module_name));

    out.push_str("export interface CertoExports {\n");
    for f in &fns {
        match fn_ts_sig(f) {
            Some(sig) => out.push_str(&format!("  {};\n", sig)),
            None      => out.push_str(&format!(
                "  // {name}: params or return type require memory management — use raw WASM exports\n",
                name = f.name.node
            )),
        }
    }
    if has_main(module) {
        out.push_str("  /** Runs the program's `main`. */\n  run(): void;\n");
    }
    out.push_str("}\n\n");
    out.push_str(
        "export interface CertoIO {\n\
        \x20 /** Called with each line the program writes to stdout (default: console.log). */\n\
        \x20 stdout?: (line: string) => void;\n\
        \x20 /** Called with each line written to stderr (default: console.error). */\n\
        \x20 stderr?: (line: string) => void;\n\
        }\n\n"
    );

    // Loader declaration
    out.push_str(
        "/**\n\
         * Load the compiled Certo WASM module.\n\
         * @param path  Path or URL to the .wasm file.\n\
         */\n\
        export declare function load(path: string | URL, io?: CertoIO): Promise<CertoExports>;\n"
    );

    out
}

/// Generate an ESM JavaScript loader.
///
/// The loader supplies the imports a module built with the runtime shim needs
/// (`env.certo_write` for `print`/`println`/`eprint`/`eprintln`, and
/// `env.certo_float_to_text` for `floatToText`), so a program that prints runs
/// in the browser. Pass `{ stdout, stderr }` callbacks to `load` to receive
/// each line; they default to `console.log` / `console.error`. If the module
/// has a `main` function the result also has `run()`.
pub fn generate_js(module: &Module, module_name: &str, _wasm_filename: &str) -> String {
    let fns = collect_pub_fns(module);
    let mut out = String::new();

    out.push_str("// Generated by certo-wasm — do not edit\n");
    out.push_str(&format!("// Module: {}\n\n", module_name));

    out.push_str(JS_LOAD_HEAD);

    for f in &fns {
        if fn_ts_sig(f).is_some() {
            let name = &f.name.node;
            let js_name = llvm_fn_name(name);
            out.push_str(&format!("    {name}: (...args) => exp.{js_name}(...args),\n",
                name    = name,
                js_name = js_name));
        }
    }
    if has_main(module) {
        out.push_str("    // Runs the program's `main`, then flushes any unterminated output line.\n");
        out.push_str("    run: () => { exp.certo_main(); flush(); },\n");
    }

    out.push_str("  };\n}\n\n");
    out.push_str(JS_HELPERS);
    out
}

const JS_LOAD_HEAD: &str = r#"export async function load(path, io = {}) {
  const bytes = typeof fetch !== 'undefined'
    ? await fetch(path).then(r => r.arrayBuffer())
    : await import('fs').then(fs => fs.promises.readFile(path));
  const sinks = {
    1: io.stdout ?? ((line) => console.log(line)),
    2: io.stderr ?? ((line) => console.error(line)),
  };
  const pending = { 1: '', 2: '' };
  const decoder = new TextDecoder();
  const encoder = new TextEncoder();
  let memory;
  const emit = (fd) => {
    let i;
    while ((i = pending[fd].indexOf('\n')) >= 0) {
      sinks[fd](pending[fd].slice(0, i));
      pending[fd] = pending[fd].slice(i + 1);
    }
  };
  const flush = () => {
    for (const fd of [1, 2]) {
      emit(fd);
      if (pending[fd] !== '') { sinks[fd](pending[fd]); pending[fd] = ''; }
    }
  };
  const env = {
    // print/println/eprint/eprintln: the shim writes raw chunks, newline included.
    certo_write: (fd, ptr, len) => {
      pending[fd] = (pending[fd] ?? '') + decoder.decode(new Uint8Array(memory.buffer, ptr, len));
      emit(fd);
    },
    // floatToText: the same shortest-round-trip rule as the native backends.
    certo_float_to_text: (x, ptr, cap) => {
      const b = encoder.encode(formatFloat(x));
      const n = Math.min(b.length, cap);
      new Uint8Array(memory.buffer, ptr, n).set(b.subarray(0, n));
      return n;
    },
  };
  const { instance } = await WebAssembly.instantiate(bytes, {
    wasi_snapshot_preview1: makeWasiStub(),
    env,
  });
  memory = instance.exports.memory;
  const exp = instance.exports;
  return {
"#;

const JS_HELPERS: &str = r#"// Float -> text, the same rule as the native backends (BACKLOG item 400): the
// fewest significant digits that read back as exactly the same number; plain
// decimal for exponents in [-5, 17), C-style exponents ("1e+21", "1.5e-07") beyond;
// whole numbers without a fractional part.
function formatFloat(x) {
  if (Number.isNaN(x)) return 'nan';
  if (!Number.isFinite(x)) return x < 0 ? '-inf' : 'inf';
  if (x === 0) return Object.is(x, -0) ? '-0' : '0';
  let p = 1;
  while (p < 17 && Number(x.toExponential(p - 1)) !== x) p++;
  const [mant, ex] = x.toExponential(p - 1).split('e');
  const exp = parseInt(ex, 10);
  if (exp >= -5 && exp < 17) return x.toFixed(Math.max(0, p - 1 - exp));
  const trim = (t) => (t.includes('.') ? t.replace(/0+$/, '').replace(/\.$/, '') : t);
  const a = Math.abs(exp);
  return `${trim(mant)}e${exp < 0 ? '-' : '+'}${a < 10 ? '0' : ''}${a}`;
}

function makeWasiStub() {
  // Minimal WASI stub for modules built for the browser target (their output
  // goes through env.certo_write, not WASI). Replace with a full WASI
  // implementation (e.g. @bjorn3/browser_wasi_shim) for a wasm32-wasi build.
  const noop = () => 0;
  return {
    fd_write: noop, fd_read: noop, fd_close: noop,
    proc_exit: code => { throw new Error(`exit(${code})`); },
    environ_get: noop, environ_sizes_get: noop,
    args_get: noop, args_sizes_get: noop,
    clock_time_get: noop, random_get: noop,
  };
}
"#;

/// Generate a simple HTML page that loads the WASM and calls exported functions
/// via a JS console — useful for quick browser testing.
pub fn generate_html(module_name: &str, js_filename: &str) -> String {
    format!(r#"<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>{name} — Certo WASM</title></head>
<body>
<h1>{name}</h1>
<pre id="output">Loading…</pre>
<script type="module">
import {{ load }} from './{js}';
const wasm = await load('./{name}.wasm');
const out = document.getElementById('output');
out.textContent = 'Module loaded. Available exports:\n' + Object.keys(wasm).join('\n');
if (wasm.run) {{
  const lines = [];
  const show = line => {{ lines.push(line); out.textContent = lines.join('\n'); }};
  const running = await load('./{name}.wasm', {{ stdout: show, stderr: show }});
  running.run();
}}
// Call your exports here, e.g.: wasm.add(1n, 2n)
</script>
</body>
</html>
"#, name = module_name, js = js_filename)
}

// ------------------------------------------------------------------ //
// Helpers
// ------------------------------------------------------------------ //

fn has_main(module: &Module) -> bool {
    module.decls.iter().any(|sd| matches!(&sd.node, Decl::Fn(f) if f.name.node == "main" && f.params.is_empty()))
}

fn collect_pub_fns(module: &Module) -> Vec<FnDecl> {
    module.decls.iter()
        .filter_map(|sd| if let Decl::Fn(f) = &sd.node { Some(f.clone()) } else { None })
        .filter(|f| f.is_pub)
        .collect()
}

/// TypeScript type for a Certo `TypeExpr`.  Returns `None` for types that
/// require linear-memory management (Text, records, …).
fn ts_type(te: &TypeExpr) -> Option<&'static str> {
    match te {
        TypeExpr::Named { path, .. } => {
            let name = path.segments.last()?.node.as_str();
            match name {
                "Int"   => Some("bigint"),   // WASM i64
                "Float" => Some("number"),   // WASM f64
                "Bool"  => Some("boolean"),  // WASM i32 (0/1)
                _       => None,             // opaque
            }
        }
        TypeExpr::Tuple { elements, .. } if elements.is_empty() => Some("void"),
        _ => None,
    }
}

/// Full TypeScript signature for a function.  Returns `None` if any param or
/// return type is opaque.
fn fn_ts_sig(f: &FnDecl) -> Option<String> {
    let ret_ts = match &f.ret_ty {
        None     => "void",
        Some(te) => ts_type(&te.node)?,
    };
    let params: Option<Vec<String>> = f.params.iter()
        .map(|p| ts_type(&p.ty.node).map(|t| format!("{}: {}", p.name.node, t)))
        .collect();
    let params = params?;
    Some(format!("{}({}): {}", f.name.node, params.join(", "), ret_ts))
}

fn llvm_fn_name(name: &str) -> String {
    format!("certo_{}", name.replace('.', "_").replace('-', "_"))
}

