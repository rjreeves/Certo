#[cfg(test)]
mod tests {
    use super::*;
    use certo_parser::parse;

    fn module(src: &str) -> Module {
        parse(src).expect("parse error")
    }

    #[test]
    fn numeric_pub_fn_appears_in_dts() {
        let m   = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let dts = generate_dts(&m, "M");
        assert!(dts.contains("add(a: bigint, b: bigint): bigint"), "missing typed sig\n{}", dts);
    }

    #[test]
    fn text_fn_is_commented_out_in_dts() {
        let m   = module("module M\npub fn greet(name: Text): Text = name\n");
        let dts = generate_dts(&m, "M");
        assert!(dts.contains("// greet:"), "expected comment for Text fn\n{}", dts);
    }

    #[test]
    fn private_fn_not_in_dts() {
        let m   = module("module M\nfn internal(x: Int): Int = x\n");
        let dts = generate_dts(&m, "M");
        assert!(!dts.contains("internal("), "private fn should not appear\n{}", dts);
    }

    #[test]
    fn js_loader_contains_export() {
        let m  = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let js = generate_js(&m, "M", "M.js");
        assert!(js.contains("add:"), "missing export in JS\n{}", js);
        assert!(js.contains("certo_add"), "missing wasm export name\n{}", js);
    }

    #[test]
    fn js_loader_supplies_the_runtime_imports() {
        let m  = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let js = generate_js(&m, "M", "M.js");
        assert!(js.contains("certo_write"), "println needs env.certo_write\n{}", js);
        assert!(js.contains("certo_float_to_text"), "floatToText needs a host formatter\n{}", js);
        assert!(js.contains("stdout") && js.contains("stderr"), "output callbacks\n{}", js);
        assert!(js.contains("function formatFloat"), "{}", js);
    }

    #[test]
    fn run_is_exposed_only_when_the_module_has_a_main() {
        let with = module("module M\npub fn main(): Unit = ()\n");
        assert!(generate_js(&with, "M", "M.js").contains("run: () => { exp.certo_main(); flush(); }"));
        assert!(generate_dts(&with, "M").contains("run(): void;"));

        let without = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        assert!(!generate_js(&without, "M", "M.js").contains("run:"));
        assert!(!generate_dts(&without, "M").contains("run()"));

        // a `main` that takes arguments can't be run with none
        let args = module("module M\nfn main(x: Int): Unit = ()\n");
        assert!(!generate_js(&args, "M", "M.js").contains("run:"));
    }

    #[test]
    fn dts_declares_the_io_callbacks() {
        let m   = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let dts = generate_dts(&m, "M");
        assert!(dts.contains("export interface CertoIO"), "{}", dts);
        assert!(dts.contains("load(path: string | URL, io?: CertoIO)"), "{}", dts);
    }

    #[test]
    fn bool_fn_typed_as_boolean() {
        let m   = module("module M\npub fn pos(x: Int): Bool = x > 0\n");
        let dts = generate_dts(&m, "M");
        assert!(dts.contains("boolean"), "Bool should be boolean\n{}", dts);
    }
}
