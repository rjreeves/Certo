#[cfg(test)]
mod tests {
    use super::*;

    const SCHEMA: &str = r#"
    {
      "module":   "UserApi",
      "base_url": "https://api.example.com",
      "auth":     "bearer",
      "endpoints": [
        {
          "name":        "get_user",
          "method":      "GET",
          "path":        "/users/{id}",
          "path_params": [{ "name": "id", "ty": "Int" }],
          "response":    "User"
        },
        {
          "name":      "list_users",
          "method":    "GET",
          "path":      "/users",
          "query_params": [{ "name": "page", "ty": "Int", "optional": true }],
          "response":  "List<User>"
        },
        {
          "name":     "create_user",
          "method":   "POST",
          "path":     "/users",
          "body":     { "ty": "CreateUserRequest" },
          "response": "User"
        },
        {
          "name":        "delete_user",
          "method":      "DELETE",
          "path":        "/users/{id}",
          "path_params": [{ "name": "id", "ty": "Int" }],
          "response":    null
        }
      ]
    }
    "#;

    fn schema() -> RestSchema { parse_schema(SCHEMA).expect("parse") }

    #[test]
    fn parse_schema_ok() {
        let s = schema();
        assert_eq!(s.module,   "UserApi");
        assert_eq!(s.endpoints.len(), 4);
    }

    #[test]
    fn module_declaration_present() {
        let src = generate_client(&schema());
        assert!(src.starts_with("module UserApi"), "wrong module header\n{}", src);
    }

    #[test]
    fn get_fn_has_async_io() {
        let src = generate_client(&schema());
        assert!(src.contains("[async, io]"), "missing effects\n{}", src);
    }

    #[test]
    fn path_param_interpolated() {
        let src = generate_client(&schema());
        assert!(src.contains("id.toString()"), "missing path interpolation\n{}", src);
    }

    #[test]
    fn post_includes_body() {
        let src = generate_client(&schema());
        assert!(src.contains("http_post("), "missing http_post\n{}", src);
        assert!(src.contains("body: CreateUserRequest"), "missing body param\n{}", src);
    }

    #[test]
    fn delete_returns_unit() {
        let src = generate_client(&schema());
        assert!(src.contains(": Unit [async, io]"), "DELETE should return Unit\n{}", src);
    }

    #[test]
    fn optional_query_param_has_question_mark() {
        let src = generate_client(&schema());
        assert!(src.contains("page: Int?"), "optional param should have ?\n{}", src);
    }

    #[test]
    fn invalid_json_gives_schema_error() {
        let err = parse_schema("not json").unwrap_err();
        assert!(matches!(err, FfiError::SchemaError(_)));
    }

    #[test]
    fn base_url_in_generated_code() {
        let src = generate_client(&schema());
        assert!(src.contains("api.example.com"), "missing base URL\n{}", src);
    }
}
