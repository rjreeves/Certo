#[cfg(test)]
mod tests {
    use super::*;
    use certo_parser::parse;

    fn module(src: &str) -> Module { parse(src).expect("parse") }

    #[test]
    fn basic_int_fn() {
        let m = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let h = generate_header(&m, None);
        assert!(h.contains("int64_t certo_add(int64_t a, int64_t b);"), "missing prototype\n{}", h);
        assert!(h.contains("#ifndef M_H"), "missing guard\n{}", h);
    }

    #[test]
    fn text_fn() {
        let m = module("module M\npub fn greet(name: Text): Text = name\n");
        let h = generate_header(&m, None);
        assert!(h.contains("const char* certo_greet(const char* name);"), "wrong text mapping\n{}", h);
    }

    #[test]
    fn private_fn_excluded() {
        let m = module("module M\nfn internal(x: Int): Int = x\n");
        let h = generate_header(&m, None);
        assert!(!h.contains("certo_internal"), "private fn must not appear\n{}", h);
    }

    #[test]
    fn unit_return_is_void() {
        let m = module("module M\npub fn doThing(): Unit = ()\n");
        let h = generate_header(&m, None);
        assert!(h.contains("void certo_doThing(void);"), "Unit should map to void\n{}", h);
    }

    #[test]
    fn custom_guard() {
        let m = module("module M\npub fn add(a: Int, b: Int): Int = a + b\n");
        let h = generate_header(&m, Some("MY_CUSTOM_GUARD_H"));
        assert!(h.contains("#ifndef MY_CUSTOM_GUARD_H"), "missing custom guard\n{}", h);
    }

    #[test]
    fn no_params_uses_void() {
        let m = module("module M\npub fn now(): Int = 0\n");
        let h = generate_header(&m, None);
        assert!(h.contains("int64_t certo_now(void);"), "no-param fn should use void\n{}", h);
    }

    #[test]
    fn export_annotation_overrides_prototype_name() {
        let m = module("module M\n@export(\"my_custom_add\")\npub fn add(a: Int, b: Int): Int = a + b\n");
        let h = generate_header(&m, None);
        assert!(h.contains("int64_t my_custom_add(int64_t a, int64_t b);"), "missing custom-named prototype\n{}", h);
        assert!(!h.contains("certo_add("), "should not also emit the default-named prototype\n{}", h);
    }
}
