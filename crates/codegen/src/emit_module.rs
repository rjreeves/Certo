use std::fmt::Write as FmtWrite;
use certo_ast::decl::{Decl, TypeBody, StateMachineDecl};
use certo_ast::module::Module;
use certo_hir::{HirFn, HirItem, lower_module};
use certo_mir::lower_fn;
use crate::emit_mir::{emit_fn_with_prefix, c_fn_name, collect_spawn_sites, emit_spawn_support, set_extern_names, LineMap};
use crate::ty_to_c::{ty_to_c, ret_ty_to_c, c_ident};

/// Options controlling C output.
#[derive(Debug, Clone, Default)]
pub struct CodegenOptions {
    /// Include the embedded runtime header inline (default: true).
    pub inline_runtime: bool,
    /// Prefix `pub fn` declarations with `CERTO_EXPORT` for shared library builds.
    pub export_public: bool,
    /// `Some((filename, source))` opts into emitting `#line` directives that
    /// map generated C back to the original `.cto` file/line, so coverage
    /// tools (`llvm-cov`) attribute results to the user's own source instead
    /// of meaningless generated-C line numbers — BACKLOG item 126. `None`
    /// (the default) for every normal `certo build`/`run`/`test` path;
    /// only `certo test --coverage`'s own C generation opts in, so ordinary
    /// compile-error messages keep pointing at the generated C as before.
    pub line_directives: Option<(String, String)>,
}

/// Emit a complete C translation unit for the given module.
pub fn emit_module(module: &Module, opts: &CodegenOptions) -> String {
    let mut out = String::new();
    let line_map: Option<LineMap> = opts.line_directives.as_ref()
        .map(|(filename, source)| LineMap::new(filename, source));

    // BACKLOG item 242 — must run before any codegen call below, since
    // `c_fn_name` consults this registry on every call.
    set_extern_names(module.decls.iter().filter_map(|sdecl| match &sdecl.node {
        Decl::Fn(f) if f.is_extern => Some(f.name.node.clone()),
        _ => None,
    }).collect());

    // All-nullary enums are represented as plain int enums (not structs). The
    // function emitters need to know which, so `match`'s `.tag` read on such a
    // value compiles to the value itself. Populated during type emission below.
    let mut nullary_enums: std::collections::HashSet<String> = std::collections::HashSet::new();

    // BACKLOG item 201 — type names that got a real, generated
    // `certo_eq_<Name>` structural-equality function (see `build_type_shapes`/
    // `ty_is_comparable` below); `emit_binop`'s `BinOp::Eq`/`NotEq` consult
    // this to call it instead of emitting an invalid bare C `==` on a struct.
    let mut eq_types: std::collections::HashSet<String> = std::collections::HashSet::new();

    // A nullary variant's own name → its parent sum type's name, for every
    // variant of every sum type (not just mixed ones) — BACKLOG item 201.
    // A bare nullary-variant *constant* reference (`Origin == Origin`) is
    // `Operand::Global`, which has no `MirLocalDecl` to recover a type
    // from; `emit_binop` consults this to find the parent type (and from
    // there, whether it's in `eq_types`) when that happens.
    let mut variant_parent: std::collections::HashMap<String, String> = std::collections::HashMap::new();

    // Build set of pub function names for export annotation.
    let pub_fns: std::collections::HashSet<&str> = module.decls.iter()
        .filter_map(|d| if let Decl::Fn(f) = &d.node { Some(f) } else { None })
        .filter(|f| f.is_pub)
        .map(|f| f.name.node.as_str())
        .collect();

    // `@export("name")` — maps a pub fn's Certo name to the custom C symbol it
    // should additionally be exported under (parser guarantees export_name
    // implies is_pub). The internal function keeps its usual mangled name
    // (`certo_<name>`) for in-module calls; a thin exported wrapper is emitted
    // separately (see `export_wrappers` below) so callers inside the module
    // aren't affected by the external symbol name.
    let export_names: std::collections::HashMap<&str, &str> = module.decls.iter()
        .filter_map(|d| if let Decl::Fn(f) = &d.node { Some(f) } else { None })
        .filter_map(|f| f.export_name.as_deref().map(|n| (f.name.node.as_str(), n)))
        .collect();

    let export = |name: &str| -> &'static str {
        let _ = name; // checked by caller
        if opts.export_public { "CERTO_EXPORT " } else { "" }
    };

    // --- Header ---
    writeln!(out, "/* Generated by Certo compiler — do not edit */").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include <stdbool.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();

    if opts.inline_runtime {
        out.push_str(RUNTIME_HEADER);
    } else {
        writeln!(out, "#include \"certo_runtime.h\"").unwrap();
    }

    writeln!(out).unwrap();

    // BACKLOG item 201 — which types can get a real, generated
    // `certo_eq_<Name>` structural-equality function, computed once up
    // front so field comparability can look *forward* too, not just
    // backward through already-emitted types.
    let type_shapes = build_type_shapes(module);

    // --- Struct definitions from `type` declarations ---
    for sdecl in &module.decls {
        if let Decl::Type(t) = &sdecl.node {
            let type_params: Vec<String> = t.type_params.iter().map(|tp| tp.name.node.clone()).collect();
            match &t.body {
                TypeBody::Record(rec) => {
                    writeln!(out, "typedef struct {{").unwrap();
                    for f in &rec.fields {
                        let cty = field_c_ty(&f.ty.node, &type_params, None);
                        writeln!(out, "    {} {};", cty, f.name.node).unwrap();
                    }
                    writeln!(out, "}} {};", c_ident(&t.name.node)).unwrap();
                    writeln!(out).unwrap();

                    // BACKLOG item 201 — a plain-value struct's `==`/`!=`
                    // don't compile in C at all (`invalid operands to
                    // binary expression`), directly contradicting the
                    // spec's own §8.4 "equality is structural" claim.
                    // Only emitted when every field (recursively) is one
                    // this function knows how to compare correctly —
                    // generic type params, and List/Option/Map/Tuple/Fn-
                    // typed fields, are deliberately excluded (a `void*`
                    // slot has no single correct comparison without the
                    // same generic-erasure machinery item 200's own design
                    // sketch describes) — `==` on such a type is left
                    // exactly as broken as before, a clean C compile
                    // error, not a silently wrong comparison.
                    if type_params.is_empty() && rec.fields.iter().all(|f| !f.optional && ty_is_comparable(&f.ty.node, &type_shapes)) {
                        let tname = c_ident(&t.name.node);
                        writeln!(out, "static inline bool certo_eq_{tname}({tname} a, {tname} b) {{").unwrap();
                        let parts: Vec<String> = rec.fields.iter()
                            .map(|f| emit_field_cmp(&format!("a.{}", f.name.node), &format!("b.{}", f.name.node), &f.ty.node, &type_shapes))
                            .collect();
                        let body = if parts.is_empty() { "true".to_string() } else { parts.join(" && ") };
                        writeln!(out, "    return {body};").unwrap();
                        writeln!(out, "}}").unwrap();
                        writeln!(out).unwrap();
                        eq_types.insert(t.name.node.clone());
                    }

                    // BACKLOG item 262 — positional record construction
                    // (spec §8.4, e.g. `Money(d"10.00", USD)`). Mirrors a
                    // sum-type variant-with-fields constructor's own
                    // codegen exactly (see the `TypeBody::Sum` arm below):
                    // an ordinary real C function, named to match how HIR/
                    // MIR reference the record type's own bare name as a
                    // call target (`c_fn_name`), taking every declared
                    // field positionally in declaration order. `computed`
                    // fields are never parameters (they have no backing
                    // storage to initialize); this matches typeck/HIR's own
                    // exclusion of them from the constructor's registered
                    // arity.
                    let tname = c_ident(&t.name.node);
                    let cname = crate::emit_mir::c_fn_name(&t.name.node);
                    let params: Vec<String> = rec.fields.iter().map(|f| {
                        let cty = field_c_ty(&f.ty.node, &type_params, None);
                        format!("{cty} {}", f.name.node)
                    }).collect();
                    let inits: Vec<String> = rec.fields.iter()
                        .map(|f| format!(".{0} = {0}", f.name.node))
                        .collect();
                    writeln!(out, "static inline {tname} {cname}({}) {{", params.join(", ")).unwrap();
                    writeln!(out, "    {tname} _v = {{ {} }};", inits.join(", ")).unwrap();
                    writeln!(out, "    return _v;").unwrap();
                    writeln!(out, "}}").unwrap();
                    writeln!(out).unwrap();
                }
                TypeBody::Sum(variants) => {
                    let tname = c_ident(&t.name.node);
                    let has_payload = variants.iter().any(|v| !v.fields.is_empty());
                    for v in variants {
                        if v.fields.is_empty() {
                            variant_parent.insert(v.name.node.clone(), t.name.node.clone());
                        }
                    }
                    if has_payload {
                        // Tagged union: a tag enum plus a struct with a payload union.
                        writeln!(out, "typedef enum {{").unwrap();
                        for v in variants {
                            writeln!(out, "    {}_{},", tname, c_ident(&v.name.node)).unwrap();
                        }
                        writeln!(out, "}} {}_tag_t;", tname).unwrap();
                        // BACKLOG item 277 — a named struct tag (not just the
                        // eventual typedef alias), so a *direct* self-
                        // referential field further down (`struct {tname}*`)
                        // can reference this same struct from inside its own
                        // body — the typedef name `{tname}` itself isn't a
                        // valid type until this whole `typedef ... ;`
                        // completes. Harmless to add unconditionally: a
                        // non-recursive payload type never references the
                        // tag at all.
                        writeln!(out, "typedef struct {} {{", tname).unwrap();
                        writeln!(out, "    {}_tag_t tag;", tname).unwrap();
                        writeln!(out, "    union {{").unwrap();
                        for v in variants {
                            if !v.fields.is_empty() {
                                writeln!(out, "        struct {{").unwrap();
                                for (i, f) in v.fields.iter().enumerate() {
                                    let fname = f.name.as_ref().map(|n| n.node.clone())
                                        .unwrap_or_else(|| format!("f{}", i));
                                    let cty = field_c_ty(&f.ty.node, &type_params, Some(t.name.node.as_str()));
                                    writeln!(out, "            {} {};", cty, fname).unwrap();
                                }
                                writeln!(out, "        }} {};", c_ident(&v.name.node).to_lowercase()).unwrap();
                            }
                        }
                        writeln!(out, "    }};").unwrap();
                        writeln!(out, "}} {};", tname).unwrap();

                        // BACKLOG item 201 — same structural-equality
                        // treatment as records, just tag-then-payload:
                        // two values only compare equal when the active
                        // variant matches *and* that variant's own fields
                        // (recursively) do. A variant with no fields needs
                        // nothing further once the tag already matched.
                        let comparable = type_params.is_empty()
                            && variants.iter().all(|v| v.fields.iter().all(|f| ty_is_comparable(&f.ty.node, &type_shapes)));
                        if comparable {
                            writeln!(out, "static inline bool certo_eq_{tname}({tname} a, {tname} b) {{").unwrap();
                            writeln!(out, "    if (a.tag != b.tag) return false;").unwrap();
                            writeln!(out, "    switch (a.tag) {{").unwrap();
                            for v in variants {
                                let member = c_ident(&v.name.node).to_lowercase();
                                let cmp = if v.fields.is_empty() {
                                    "true".to_string()
                                } else {
                                    v.fields.iter().enumerate().map(|(i, f)| {
                                        let fname = f.name.as_ref().map(|n| n.node.clone()).unwrap_or_else(|| format!("f{i}"));
                                        emit_field_cmp(&format!("a.{member}.{fname}"), &format!("b.{member}.{fname}"), &f.ty.node, &type_shapes)
                                    }).collect::<Vec<_>>().join(" && ")
                                };
                                writeln!(out, "        case {tname}_{}: return {cmp};", c_ident(&v.name.node)).unwrap();
                            }
                            writeln!(out, "        default: return true;").unwrap();
                            writeln!(out, "    }}").unwrap();
                            writeln!(out, "}}").unwrap();
                            writeln!(out).unwrap();
                            eq_types.insert(t.name.node.clone());
                        }
                    } else {
                        // All-nullary: a plain integer enum, so values are pointer-sized
                        // and can flow through Result / List / tuple slots unchanged.
                        writeln!(out, "typedef enum {{").unwrap();
                        for v in variants {
                            writeln!(out, "    {}_{},", tname, c_ident(&v.name.node)).unwrap();
                        }
                        writeln!(out, "}} {};", tname).unwrap();
                        nullary_enums.insert(t.name.node.clone());
                    }
                    // Emit unit-variant constants.
                    // Use snake_case (via c_fn_name logic) to match how the codegen references globals.
                    for v in variants {
                        if v.fields.is_empty() {
                            let vname = c_ident(&v.name.node);
                            let cname = crate::emit_mir::c_fn_name(&v.name.node); // e.g. certo_red
                            if has_payload {
                                // Struct representation: initialise the tag field.
                                writeln!(out, "static const {tname} {cname} = {{ .tag = {tname}_{vname} }};").unwrap();
                            } else {
                                // Integer representation: the constant is the tag value.
                                writeln!(out, "static const {tname} {cname} = {tname}_{vname};").unwrap();
                            }
                        } else {
                            // Emit constructor function. The function name must match how
                            // call sites reference it (`c_fn_name`, snake_case), while the
                            // tag and union member keep the `c_ident` form.
                            let vname = c_ident(&v.name.node);
                            let cname = crate::emit_mir::c_fn_name(&v.name.node);
                            let params: Vec<String> = v.fields.iter().enumerate().map(|(i, f)| {
                                let fname = f.name.as_ref().map(|n| n.node.clone()).unwrap_or_else(|| format!("f{i}"));
                                let cty = field_c_ty(&f.ty.node, &type_params, Some(t.name.node.as_str()));
                                format!("{cty} {fname}")
                            }).collect();
                            let inits: Vec<String> = v.fields.iter().enumerate().map(|(i, f)| {
                                let fname = f.name.as_ref().map(|n| n.node.clone()).unwrap_or_else(|| format!("f{i}"));
                                format!(".{fname} = {fname}")
                            }).collect();
                            writeln!(out, "static inline {tname} {cname}({}) {{", params.join(", ")).unwrap();
                            writeln!(out, "    {tname} _v = {{ .tag = {tname}_{vname}, .{} = {{ {} }} }};",
                                vname.to_lowercase(), inits.join(", ")).unwrap();
                            writeln!(out, "    return _v;").unwrap();
                            writeln!(out, "}}").unwrap();
                        }
                    }
                    writeln!(out).unwrap();
                }
                TypeBody::Alias(_) => {} // aliases don't generate structs
            }
        }
    }

    // --- State machine type and function definitions ---
    for sdecl in &module.decls {
        if let Decl::StateMachine(sm) = &sdecl.node {
            emit_statemachine(sm, &mut out);
        }
    }

    // --- Lower to HIR then MIR and emit functions ---
    let hir = match lower_module(module) {
        Ok(h)  => h,
        Err(e) => {
            writeln!(out, "/* HIR lowering errors: {} */", e.len()).unwrap();
            return out;
        }
    };

    // Lower all functions to MIR once so the actual return types are known.
    // HirFn.ret_ty is Ty::Error (a placeholder) — the MIR return slot (local 0)
    // holds the real type after lower_fn() infers it from the function body.
    let mut lifted_fns: Vec<certo_mir::MirFn> = Vec::new();
    let fn_mirs: Vec<(certo_mir::MirFn, &str)> = hir.items.iter()
        .filter_map(|item| if let HirItem::Fn(f) = item {
            let (mir, lifted) = lower_fn(f, &hir.record_field_types, &hir.variant_field_types, &hir.fn_param_tys, &hir.fn_ret_tys, &hir.variant_to_type);
            lifted_fns.extend(lifted);
            Some((mir, f.name.as_str()))
        } else {
            None
        })
        .collect();

    // A module-level `val name = <expr>` whose initializer isn't a simple
    // compile-time-constant literal previously compiled to a bare
    // `static T name = /* expr */0;` — `const_expr_to_c`'s fallback for
    // anything it can't render as a literal C expression — silently
    // discarding the real initializer entirely and leaving `name` at a
    // placeholder zero/NULL forever. Confirmed with a direct repro
    // (`val conn = dbConnect(...)` always NULL, `dbError` always
    // "connection failed") while building BACKLOG item 154, then found to
    // be fully general — `fn five(): Int = 5` / `val x = five()` prints `0`,
    // not `5` — not specific to DB or the REPL at all (BACKLOG item 168).
    //
    // Fixed by reusing the existing function-lowering pipeline instead of
    // trying to render an arbitrary expression as a single C expression (the
    // dead-end `const_expr_to_c`/`simple_expr_to_c` were already attempting
    // and abandoning): each such `val` gets a synthesized zero-arg
    // `__certo_init_<name>` function whose body *is* the real initializer,
    // lowered and emitted exactly like an ordinary function (so it gets
    // real MIR, real boxing/unboxing, real multi-statement bodies — nothing
    // new to prove correct). The global itself is declared uninitialized
    // (`static T name;`, zero-init by plain C semantics) and assigned from
    // the init function's return value in the generated bootstrap, right
    // after `certo_main_init(...)` and before the user's own `main()` body
    // runs — see the `has_main` block below. Literal initializers are left
    // completely untouched (still real, valid C constant expressions,
    // zero behavior change, zero risk).
    let is_simple_const_literal = |value: &certo_hir::HirExpr| {
        matches!(&value.kind,
            certo_hir::HirExprKind::Int(_) | certo_hir::HirExprKind::Float(_) |
            certo_hir::HirExprKind::Bool(_) | certo_hir::HirExprKind::Str(_) |
            certo_hir::HirExprKind::Unit)
    };
    let mut const_init_fns: Vec<(String, certo_mir::MirFn)> = Vec::new();
    for item in &hir.items {
        if let HirItem::Const(c) = item {
            if !is_simple_const_literal(&c.value) {
                let init_fn = HirFn {
                    id: 0,
                    name: format!("__certo_init_{}", c.name),
                    params: vec![],
                    ret_ty: certo_typeck::Ty::Error,
                    body: Some(c.value.clone()),
                    span: c.span,
                };
                let (mir, lifted) = lower_fn(&init_fn, &hir.record_field_types, &hir.variant_field_types, &hir.fn_param_tys, &hir.fn_ret_tys, &hir.variant_to_type);
                lifted_fns.extend(lifted);
                const_init_fns.push((c.name.clone(), mir));
            }
        }
    }

    // Forward declarations — use MIR local[0].ty for the return type.
    // Also collect signatures for any `@export("name")` wrapper (emitted
    // below, after all forward declarations exist for it to call into).
    let mut export_wrappers: Vec<String> = Vec::new();
    for (mir, _) in &fn_mirs {
        let ret_ty = mir.locals.first().map(|l| &l.ty).unwrap_or(&certo_typeck::Ty::Unit);
        let ret_c  = ret_ty_to_c(ret_ty);
        let arg_tys: Vec<(String, u32)> = mir.locals.iter().skip(1).take(mir.param_count)
            .map(|l| (ty_to_c(&l.ty), l.id))
            .collect();
        let params: Vec<String> = arg_tys.iter().map(|(ty, id)| format!("{} _l{}", ty, id)).collect();
        let param_str = if params.is_empty() { "void".into() } else { params.join(", ") };
        let pfx = if pub_fns.contains(mir.name.as_str()) { export(&mir.name) } else { "" };
        writeln!(out, "{}{} {}({});", pfx, ret_c, c_fn_name(&mir.name), param_str).unwrap();
        if let Some(export_name) = export_names.get(mir.name.as_str()) {
            let args: Vec<String> = arg_tys.iter().map(|(_, id)| format!("_l{}", id)).collect();
            export_wrappers.push(format!("{}{} {}({}) {{ return {}({}); }}",
                export(export_name), ret_c, c_ident(export_name), param_str, c_fn_name(&mir.name), args.join(", ")));
        }
    }
    // Emit the exported wrappers: a thin function under the custom C symbol
    // name that just forwards to the internal `certo_<name>` definition.
    for wrapper in &export_wrappers {
        writeln!(out, "{}", wrapper).unwrap();
    }
    // Forward-declare `extern "C"` FFI functions. They have no Certo body; the
    // definition is provided by a library linked via `--link`. Emitting an
    // explicit prototype (rather than relying on an implicit declaration, which
    // C assumes returns `int`) is essential so the 64-bit Int ABI is correct.
    for sdecl in &module.decls {
        if let Decl::Fn(f) = &sdecl.node {
            if !f.is_extern { continue; }
            let ret_c = match &f.ret_ty {
                Some(ann) => ast_ty_to_c_str(&ann.node),
                None      => "certo_unit_t".into(),
            };
            let params: Vec<String> = f.params.iter()
                .map(|p| ast_ty_to_c_str(&p.ty.node))
                .collect();
            let param_str = if params.is_empty() { "void".into() } else { params.join(", ") };
            writeln!(out, "{} {}({});", ret_c, c_fn_name(&f.name.node), param_str).unwrap();
        }
    }
    // Forward-declare lifted lambdas.
    for mir in &lifted_fns {
        let ret_ty = mir.locals.first().map(|l| &l.ty).unwrap_or(&certo_typeck::Ty::Unit);
        let ret_c  = ret_ty_to_c(ret_ty);
        let params: Vec<String> = mir.locals.iter().skip(1).take(mir.param_count)
            .map(|l| format!("{} _l{}", ty_to_c(&l.ty), l.id))
            .collect();
        let param_str = if params.is_empty() { "void".into() } else { params.join(", ") };
        writeln!(out, "static {} {}({});", ret_c, c_fn_name(&mir.name), param_str).unwrap();
    }
    // Forward-declare the synthesized `__certo_init_<name>` functions for any
    // module-level `val` with a non-literal initializer (BACKLOG item 168).
    for (_, mir) in &const_init_fns {
        let ret_ty = mir.locals.first().map(|l| &l.ty).unwrap_or(&certo_typeck::Ty::Unit);
        let ret_c  = ret_ty_to_c(ret_ty);
        writeln!(out, "static {} {}(void);", ret_c, c_fn_name(&mir.name)).unwrap();
    }
    writeln!(out).unwrap();

    // Concurrency support: per-spawn-call-site context structs + thread workers.
    // Emitted after all forward declarations so workers can call any function,
    // and before the function bodies that reference them.
    {
        let mut emitted_joins: std::collections::HashSet<String> = std::collections::HashSet::new();
        let mut any = false;
        let mut support = String::new();
        for (mir, _) in &fn_mirs {
            let sites = collect_spawn_sites(mir);
            if !sites.is_empty() { any = true; }
            emit_spawn_support(&sites, &mut emitted_joins, &mut support);
        }
        for mir in &lifted_fns {
            let sites = collect_spawn_sites(mir);
            if !sites.is_empty() { any = true; }
            emit_spawn_support(&sites, &mut emitted_joins, &mut support);
        }
        if any {
            out.push_str("/* ---- spawn workers ---- */\n");
            out.push_str(&support);
            writeln!(out).unwrap();
        }
    }

    // Emit lifted lambda bodies before user functions.
    for mir in &lifted_fns {
        emit_fn_with_prefix(mir, "static ", &nullary_enums, &eq_types, &variant_parent, line_map.as_ref(), &mut out);
        writeln!(out).unwrap();
    }
    // `__certo_init_<name>` function *bodies* are deliberately NOT emitted
    // here alongside lifted lambdas (only forward-declared above) — unlike a
    // lifted lambda, an init function's body can reference *other*
    // module-level globals (`val twenty = double(ten)`), which — like any
    // top-level Certo declaration — only exist in the generated C once their
    // own `static T name;` line has been emitted. Emitting every init body
    // in one early batch, before any global's declaration, produced a real,
    // confirmed "undeclared identifier" compile error for exactly that case.
    // Each init function's body is instead emitted below, in the interleaved
    // Const/Fn loop, at the same point as its own const's declaration — the
    // same source-order-dependent rule ordinary top-level Certo code already
    // has (a `val` must be declared before something later in the file uses
    // it), not a new limitation.

    // Emit function bodies from cached MIR.
    // Interleave any non-Fn HIR items (Const) at the right position.
    let const_init_fn_by_name: std::collections::HashMap<&str, &certo_mir::MirFn> =
        const_init_fns.iter().map(|(name, mir)| (name.as_str(), mir)).collect();
    {
        let mut mir_iter = fn_mirs.into_iter();
        for item in &hir.items {
            match item {
            HirItem::Fn(_) => {
                if let Some((mir, name)) = mir_iter.next() {
                    let pfx = if pub_fns.contains(name) { export(name) } else { "" };
                    emit_fn_with_prefix(&mir, pfx, &nullary_enums, &eq_types, &variant_parent, line_map.as_ref(), &mut out);
                    writeln!(out).unwrap();
                }
            }
            HirItem::Const(c) => {
                // Module-level constants become static C globals.
                if let Some(init_mir) = const_init_fn_by_name.get(c.name.as_str()) {
                    // Non-literal initializer (BACKLOG item 168) — declared
                    // uninitialized (zero-init by plain C semantics) and
                    // really assigned from `__certo_init_<name>()` in the
                    // bootstrap below, before `main()`'s own body runs. Use
                    // the init function's own inferred return type — more
                    // accurate than `const_expr_ty`'s crude non-literal
                    // fallback (`void*` for anything it doesn't recognize).
                    let cty = init_mir.locals.first().map(|l| ty_to_c(&l.ty)).unwrap_or_else(|| "void*".into());
                    writeln!(out, "static {} {};", cty, c_fn_name(&c.name)).unwrap();
                    // The init function's own body, emitted here (not in one
                    // early batch) so any *other* global it references has
                    // already been declared, per the doc comment above.
                    emit_fn_with_prefix(*init_mir, "static ", &nullary_enums, &eq_types, &variant_parent, line_map.as_ref(), &mut out);
                    writeln!(out).unwrap();
                } else {
                    // Use the expression type when the declared type is unknown (Ty::Error).
                    let cty = if matches!(c.ty, certo_typeck::Ty::Error) {
                        const_expr_ty(&c.value)
                    } else {
                        ty_to_c(&c.ty)
                    };
                    writeln!(out, "static {} {} = {};", cty, c_fn_name(&c.name),
                        const_expr_to_c(&c.value)).unwrap();
                }
            }
            }
        }
    }

    // If the module has a `main` function, emit a C main() that bootstraps
    // argv and calls it.
    let has_main = module.decls.iter().any(|d| {
        matches!(&d.node, Decl::Fn(f) if f.name.node == "main")
    });
    if has_main {
        // Real initialization for any module-level `val` with a non-literal
        // initializer (BACKLOG item 168) — run once, before the user's own
        // `main()` body, so every later reference sees the real computed
        // value rather than the zero/NULL the global starts as.
        let mut global_inits = String::new();
        for (name, mir) in &const_init_fns {
            writeln!(global_inits, "    {} = {}();", c_fn_name(name), c_fn_name(&mir.name)).unwrap();
        }
        // On Windows emit a wmain entry point so the CRT passes wchar_t** argv,
        // which is derived directly from CommandLineToArgvW — immune to shells
        // (Git Bash, PowerShell, cmd) stripping or mangling quoted arguments.
        writeln!(out, "#ifdef _WIN32").unwrap();
        writeln!(out, "int wmain(int argc, wchar_t** argv) {{").unwrap();
        writeln!(out, "    char** u8 = (char**)malloc((size_t)argc * sizeof(char*));").unwrap();
        writeln!(out, "    for (int i = 0; i < argc; i++) {{").unwrap();
        writeln!(out, "        int n = WideCharToMultiByte(CP_UTF8,0,argv[i],-1,NULL,0,NULL,NULL);").unwrap();
        writeln!(out, "        u8[i] = (char*)malloc((size_t)n);").unwrap();
        writeln!(out, "        WideCharToMultiByte(CP_UTF8,0,argv[i],-1,u8[i],n,NULL,NULL);").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "    certo_main_init(argc, (const char**)u8);").unwrap();
        write!(out, "{}", global_inits).unwrap();
        writeln!(out, "    certo_main();").unwrap();
        writeln!(out, "    return 0;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out, "int WINAPI WinMain(HINSTANCE hInstance, HINSTANCE hPrevInstance, LPSTR lpCmdLine, int nCmdShow) {{").unwrap();
        writeln!(out, "    int argc = 0;").unwrap();
        writeln!(out, "    wchar_t** argv = CommandLineToArgvW(GetCommandLineW(), &argc);").unwrap();
        writeln!(out, "    return wmain(argc, argv);").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out, "#else").unwrap();
        writeln!(out, "int main(int argc, const char** argv) {{").unwrap();
        writeln!(out, "    certo_main_init(argc, argv);").unwrap();
        write!(out, "{}", global_inits).unwrap();
        writeln!(out, "    certo_main();").unwrap();
        writeln!(out, "    return 0;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out, "#endif").unwrap();
    }

    out
}

