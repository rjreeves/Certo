fn ast_ty_to_c_str(te: &certo_ast::types::TypeExpr) -> String {
    use certo_ast::types::TypeExpr;
    match te {
        TypeExpr::Named { path, .. } => {
            let name = path.segments.last().map(|s| s.node.as_str()).unwrap_or("void");
            match name {
                "Int"     => "int64_t".into(),
                "Float"   => "double".into(),
                "Decimal" => "certo_decimal_t".into(),
                "Bool"    => "bool".into(),
                "Text"    => "certo_text_t".into(),
                "Unit"    => "certo_unit_t".into(),
                "UUID"    => "certo_uuid_t".into(),
                other     => c_ident(other),
            }
        }
        TypeExpr::Option { .. }  => "certo_option_t".into(),
        TypeExpr::Tuple { .. }   => "certo_tuple_t".into(),
        TypeExpr::Fn { .. }      => "certo_fn_t".into(),
        TypeExpr::Record { .. }  => "void*".into(),
        TypeExpr::Ptr { inner, .. } => format!("{}*", ast_ty_to_c_str(&inner.node)),
        TypeExpr::Param { .. }   => "void*".into(),
    }
}

fn const_expr_to_c(expr: &certo_hir::HirExpr) -> String {
    use certo_hir::HirExprKind;
    match &expr.kind {
        HirExprKind::Int(n)     => n.to_string(),
        HirExprKind::Float(f)   => format!("{:.}", f),
        HirExprKind::Bool(b)    => if *b { "true".into() } else { "false".into() },
        HirExprKind::Str(s)     => format!("CERTO_STR(\"{}\")", s),
        HirExprKind::Unit       => "CERTO_UNIT".into(),
        _                       => "/* expr */0".into(),
    }
}

