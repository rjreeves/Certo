/// Options controlling C output.
#[derive(Debug, Clone, Default)]
pub struct CodegenOptions {
    /// Include the embedded runtime header inline (default: true).
    pub inline_runtime: bool,
    /// Prefix `pub fn` declarations with `CERTO_EXPORT` for shared library builds.
    pub export_public: bool,
}

/// Emit a complete C translation unit for the given module.
pub fn emit_module(module: &Module, opts: &CodegenOptions) -> String {
    let mut out = String::new();

    // Build set of pub function names for export annotation.
    let pub_fns: std::collections::HashSet<&str> = module.decls.iter()
        .filter_map(|d| if let Decl::Fn(f) = &d.node { Some(f) } else { None })
        .filter(|f| f.is_pub)
        .map(|f| f.name.node.as_str())
        .collect();

    let export = |name: &str| -> &'static str {
        let _ = name; // checked by caller
        if opts.export_public { "CERTO_EXPORT " } else { "" }
    };

    // --- Header ---
    writeln!(out, "/* Generated by Certo compiler — do not edit */").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include <stdbool.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();

    if opts.inline_runtime {
        out.push_str(RUNTIME_HEADER);
    } else {
        writeln!(out, "#include \"certo_runtime.h\"").unwrap();
    }

    writeln!(out).unwrap();

    // --- Struct definitions from `type` declarations ---
    for sdecl in &module.decls {
        if let Decl::Type(t) = &sdecl.node {
            match &t.body {
                TypeBody::Record(rec) => {
                    writeln!(out, "typedef struct {{").unwrap();
                    for f in &rec.fields {
                        let cty = ast_ty_to_c_str(&f.ty.node);
                        writeln!(out, "    {} {};", cty, f.name.node).unwrap();
                    }
                    writeln!(out, "}} {};", c_ident(&t.name.node)).unwrap();
                    writeln!(out).unwrap();
                }
                TypeBody::Sum(variants) => {
                    let tname = c_ident(&t.name.node);
                    // Emit tag enum.
                    writeln!(out, "typedef enum {{").unwrap();
                    for v in variants {
                        writeln!(out, "    {}_{},", tname, c_ident(&v.name.node)).unwrap();
                    }
                    writeln!(out, "}} {}_tag_t;", tname).unwrap();
                    // Emit tagged union struct.
                    writeln!(out, "typedef struct {{").unwrap();
                    writeln!(out, "    {}_tag_t tag;", tname).unwrap();
                    let has_payload = variants.iter().any(|v| !v.fields.is_empty());
                    if has_payload {
                        writeln!(out, "    union {{").unwrap();
                        for v in variants {
                            if !v.fields.is_empty() {
                                writeln!(out, "        struct {{").unwrap();
                                for (i, f) in v.fields.iter().enumerate() {
                                    let fname = f.name.as_ref().map(|n| n.node.clone())
                                        .unwrap_or_else(|| format!("f{}", i));
                                    let cty = ast_ty_to_c_str(&f.ty.node);
                                    writeln!(out, "            {} {};", cty, fname).unwrap();
                                }
                                writeln!(out, "        }} {};", c_ident(&v.name.node).to_lowercase()).unwrap();
                            }
                        }
                        writeln!(out, "    }};").unwrap();
                    }
                    writeln!(out, "}} {};", tname).unwrap();
                    // Emit unit-variant constants.
                    // Use snake_case (via c_fn_name logic) to match how the codegen references globals.
                    for v in variants {
                        if v.fields.is_empty() {
                            let vname = c_ident(&v.name.node);
                            let cname = crate::emit_mir::c_fn_name(&v.name.node); // e.g. certo_red
                            writeln!(out, "static const {tname} {cname} = {{ .tag = {tname}_{vname} }};").unwrap();
                        } else {
                            // Emit constructor function.
                            let vname = c_ident(&v.name.node);
                            let params: Vec<String> = v.fields.iter().enumerate().map(|(i, f)| {
                                let fname = f.name.as_ref().map(|n| n.node.clone()).unwrap_or_else(|| format!("f{i}"));
                                let cty = ast_ty_to_c_str(&f.ty.node);
                                format!("{cty} {fname}")
                            }).collect();
                            let inits: Vec<String> = v.fields.iter().enumerate().map(|(i, f)| {
                                let fname = f.name.as_ref().map(|n| n.node.clone()).unwrap_or_else(|| format!("f{i}"));
                                format!(".{fname} = {fname}")
                            }).collect();
                            writeln!(out, "static inline {tname} certo_{vname}({}) {{", params.join(", ")).unwrap();
                            writeln!(out, "    {tname} _v = {{ .tag = {tname}_{vname}, .{} = {{ {} }} }};",
                                vname.to_lowercase(), inits.join(", ")).unwrap();
                            writeln!(out, "    return _v;").unwrap();
                            writeln!(out, "}}").unwrap();
                        }
                    }
                    writeln!(out).unwrap();
                }
                TypeBody::Alias(_) => {} // aliases don't generate structs
            }
        }
    }

    // --- State machine type and function definitions ---
    for sdecl in &module.decls {
        if let Decl::StateMachine(sm) = &sdecl.node {
            emit_statemachine(sm, &mut out);
        }
    }

    // --- Lower to HIR then MIR and emit functions ---
    let hir = match lower_module(module) {
        Ok(h)  => h,
        Err(e) => {
            writeln!(out, "/* HIR lowering errors: {} */", e.len()).unwrap();
            return out;
        }
    };

    // Lower all functions to MIR once so the actual return types are known.
    // HirFn.ret_ty is Ty::Error (a placeholder) — the MIR return slot (local 0)
    // holds the real type after lower_fn() infers it from the function body.
    let fn_mirs: Vec<(certo_mir::MirFn, &str)> = hir.items.iter()
        .filter_map(|item| if let HirItem::Fn(f) = item {
            Some((lower_fn(f), f.name.as_str()))
        } else {
            None
        })
        .collect();

    // Forward declarations — use MIR local[0].ty for the return type.
    for (mir, _) in &fn_mirs {
        let ret_ty = mir.locals.first().map(|l| &l.ty).unwrap_or(&certo_typeck::Ty::Unit);
        let ret_c  = ret_ty_to_c(ret_ty);
        let params: Vec<String> = mir.locals.iter().skip(1).take(mir.param_count)
            .map(|l| format!("{} _l{}", ty_to_c(&l.ty), l.id))
            .collect();
        let param_str = if params.is_empty() { "void".into() } else { params.join(", ") };
        let pfx = if pub_fns.contains(mir.name.as_str()) { export(&mir.name) } else { "" };
        writeln!(out, "{}{} {}({});", pfx, ret_c, c_fn_name(&mir.name), param_str).unwrap();
    }
    writeln!(out).unwrap();

    // Emit function bodies from cached MIR.
    // Interleave any non-Fn HIR items (Const) at the right position.
    {
        let mut mir_iter = fn_mirs.into_iter();
        for item in &hir.items {
            match item {
            HirItem::Fn(_) => {
                if let Some((mir, name)) = mir_iter.next() {
                    let pfx = if pub_fns.contains(name) { export(name) } else { "" };
                    emit_fn_with_prefix(&mir, pfx, &mut out);
                    writeln!(out).unwrap();
                }
            }
            HirItem::Const(c) => {
                // Module-level constants become static C globals.
                let cty = ty_to_c(&c.ty);
                writeln!(out, "static {} {} = {};", cty, c_ident(&c.name),
                    const_expr_to_c(&c.value)).unwrap();
            }
            }
        }
    }

    // If the module has a `main` function, emit a C main() that bootstraps
    // argv and calls it.
    let has_main = module.decls.iter().any(|d| {
        matches!(&d.node, Decl::Fn(f) if f.name.node == "main")
    });
    if has_main {
        // On Windows emit a wmain entry point so the CRT passes wchar_t** argv,
        // which is derived directly from CommandLineToArgvW — immune to shells
        // (Git Bash, PowerShell, cmd) stripping or mangling quoted arguments.
        writeln!(out, "#ifdef _WIN32").unwrap();
        writeln!(out, "int wmain(int argc, wchar_t** argv) {{").unwrap();
        writeln!(out, "    char** u8 = (char**)malloc((size_t)argc * sizeof(char*));").unwrap();
        writeln!(out, "    for (int i = 0; i < argc; i++) {{").unwrap();
        writeln!(out, "        int n = WideCharToMultiByte(CP_UTF8,0,argv[i],-1,NULL,0,NULL,NULL);").unwrap();
        writeln!(out, "        u8[i] = (char*)malloc((size_t)n);").unwrap();
        writeln!(out, "        WideCharToMultiByte(CP_UTF8,0,argv[i],-1,u8[i],n,NULL,NULL);").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "    certo_main_init(argc, (const char**)u8);").unwrap();
        writeln!(out, "    certo_main();").unwrap();
        writeln!(out, "    return 0;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out, "#else").unwrap();
        writeln!(out, "int main(int argc, const char** argv) {{").unwrap();
        writeln!(out, "    certo_main_init(argc, argv);").unwrap();
        writeln!(out, "    certo_main();").unwrap();
        writeln!(out, "    return 0;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out, "#endif").unwrap();
    }

    out
}

