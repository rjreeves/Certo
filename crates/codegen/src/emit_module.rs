/// The shape of a user-declared `type` needed to decide whether its own
/// values can be compared with `==`, and if so, how.
enum TypeShape<'a> {
    Record(&'a [certo_ast::decl::RecordFieldDef]),
    NullaryEnum,
    PayloadEnum(&'a [certo_ast::decl::SumVariant]),
}

/// One pass over every `type` declaration, before any C is emitted, so
/// `ty_is_comparable` can look *forward* to a type declared later in the
/// file too, not just backward through whatever's already been emitted.
/// `ty_is_comparable` itself (via `ty_is_comparable_inner`) is the one that
/// guards against a cyclic type — BACKLOG item 259 found a self-referential
/// *sum* type (`Node(left: Tree, right: Tree)`, a perfectly valid recursive
/// data structure) is not the "already an infinite-size C struct, so it's
/// someone else's problem" case this comment used to assume: a payload
/// field needing heap-boxing is already stored as a pointer in C, so the
/// struct itself is finite and compiles fine — it was `ty_is_comparable`'s
/// own unguarded structural recursion through the *declared* field types
/// (not the C memory layout) that looped forever, a real Rust stack
/// overflow in the compiler itself, confirmed live via `certo build` on
/// the spec's own `Tree` example.
fn build_type_shapes(module: &Module) -> std::collections::HashMap<String, TypeShape<'_>> {
    let mut shapes = std::collections::HashMap::new();
    for sdecl in &module.decls {
        if let Decl::Type(t) = &sdecl.node {
            if !t.type_params.is_empty() { continue; } // generic — not comparable, see ty_is_comparable
            match &t.body {
                TypeBody::Record(rec) => { shapes.insert(t.name.node.clone(), TypeShape::Record(&rec.fields)); }
                TypeBody::Sum(variants) => {
                    let has_payload = variants.iter().any(|v| !v.fields.is_empty());
                    shapes.insert(t.name.node.clone(),
                        if has_payload { TypeShape::PayloadEnum(variants) } else { TypeShape::NullaryEnum });
                }
                TypeBody::Alias(_) => {}
            }
        }
    }
    shapes
}

/// Can a value of this type be compared with `==`/`!=` at all, given this
/// codebase's current C representation? Scalars/Text/Decimal/UUID always
/// can; a user record/enum can when every one of its own fields
/// (recursively) can. Deliberately conservative — an `optional` field, a
/// generic type param slot (erased to `void*`), and every
/// List/Option/Map/Tuple/Fn-typed field are all "no": each is stored as an
/// opaque pointer with no single correct comparison without the same
/// generic-erasure machinery item 200's own design sketch describes.
fn ty_is_comparable(te: &certo_ast::types::TypeExpr, shapes: &std::collections::HashMap<String, TypeShape<'_>>) -> bool {
    let mut visiting = std::collections::HashSet::new();
    ty_is_comparable_inner(te, shapes, &mut visiting)
}

/// The real recursive worker behind `ty_is_comparable` — split out purely
/// to thread `visiting` (BACKLOG item 259) without changing that function's
/// own two-arg call sites above. `visiting` is the set of type names whose
/// own field-comparability check is *currently in progress* on this call
/// stack — a self-referential sum type (`Node(left: Tree, right: Tree)`,
/// spec §3.3's own `Tree<T>` example, a perfectly valid recursive data
/// structure since a payload field needing heap-boxing is already stored as
/// a pointer in C, not inline) previously recursed into the exact same
/// `ty_is_comparable(Tree, shapes)` call forever — a real, direct Rust
/// stack overflow in the compiler itself, confirmed live via `certo build`
/// on the spec's own example. Hitting a name already in `visiting` means a
/// cycle was found before any base case — conservatively "not comparable"
/// (matching this function's own already-established conservative stance
/// for anything without a single correct comparison), not a crash.
fn ty_is_comparable_inner(
    te: &certo_ast::types::TypeExpr,
    shapes: &std::collections::HashMap<String, TypeShape<'_>>,
    visiting: &mut std::collections::HashSet<String>,
) -> bool {
    use certo_ast::types::TypeExpr;
    match te {
        TypeExpr::Named { path, args, .. } => {
            if !args.is_empty() { return false; } // List<T>/Map<K,V>/a user generic instantiation
            let name = path.segments.last().map(|s| s.node.as_str()).unwrap_or("");
            match name {
                "Int" | "Float" | "Bool" | "Unit" | "Text" | "BoundedText" | "Decimal" | "UUID" => true,
                _ if visiting.contains(name) => false,
                _ => match shapes.get(name) {
                    Some(TypeShape::Record(fields)) => {
                        visiting.insert(name.to_string());
                        let result = fields.iter().all(|f| !f.optional && ty_is_comparable_inner(&f.ty.node, shapes, visiting));
                        visiting.remove(name);
                        result
                    }
                    Some(TypeShape::NullaryEnum) => true,
                    Some(TypeShape::PayloadEnum(variants)) => {
                        visiting.insert(name.to_string());
                        let result = variants.iter().all(|v| v.fields.iter().all(|f| ty_is_comparable_inner(&f.ty.node, shapes, visiting)));
                        visiting.remove(name);
                        result
                    }
                    None => false, // unknown name (a stdlib opaque type like DateTime, or truly undeclared)
                }
            }
        }
        TypeExpr::DecimalParam { .. } => true,
        TypeExpr::BoundedTextParam { .. } => true,
        _ => false, // Option/Tuple/Fn/anonymous Record/Ptr/Param — not comparable
    }
}

/// The C expression comparing `a`/`b` of this type — only ever called
/// after `ty_is_comparable` has already confirmed it's possible.
fn emit_field_cmp(a: &str, b: &str, te: &certo_ast::types::TypeExpr, shapes: &std::collections::HashMap<String, TypeShape<'_>>) -> String {
    use certo_ast::types::TypeExpr;
    match te {
        TypeExpr::Named { path, .. } => {
            let name = path.segments.last().map(|s| s.node.as_str()).unwrap_or("");
            match name {
                "Text" | "BoundedText" => format!("certo_text_eq({a}, {b})"),
                "UUID" => format!("certo_uuid_eq({a}, {b})"),
                "Decimal" => format!("certo_decimal_eq({a}, {b})"),
                _ => match shapes.get(name) {
                    Some(TypeShape::Record(_)) | Some(TypeShape::PayloadEnum(_)) =>
                        format!("certo_eq_{}({a}, {b})", c_ident(name)),
                    _ => format!("({a} == {b})"), // Int/Float/Bool/Unit, or a nullary enum (already a plain int)
                }
            }
        }
        TypeExpr::DecimalParam { .. } => format!("certo_decimal_eq({a}, {b})"),
        TypeExpr::BoundedTextParam { .. } => format!("certo_text_eq({a}, {b})"),
        _ => unreachable!("emit_field_cmp called on a type ty_is_comparable rejected"),
    }
}

fn ast_ty_to_c_str(te: &certo_ast::types::TypeExpr) -> String {
    use certo_ast::types::TypeExpr;
    match te {
        TypeExpr::Named { path, args, .. } => {
            // Any generic instantiation — a built-in (`List<Int>`, `Map<K,V>`,
            // an explicit `Option<T>`/`Result<A,B>`) or a user's own
            // (`Box<T>`) — is an opaque pointer everywhere else in codegen
            // (`ty_to_c` on the resolved `Ty`); a bare `Named` name lookup
            // below would either hit the wrong branch or fall through to a
            // literal (and undeclared) C type name like `List`.
            if !args.is_empty() { return "void*".into(); }
            let name = path.segments.last().map(|s| s.node.as_str()).unwrap_or("void");
            match name {
                "Int"     => "int64_t".into(),
                "Float"   => "double".into(),
                "Decimal" => "certo_decimal_t".into(),
                "Bool"    => "bool".into(),
                "Text"    => "certo_text_t".into(),
                "BoundedText" => "certo_text_t".into(),
                "Unit"    => "certo_unit_t".into(),
                "UUID"    => "certo_uuid_t".into(),
                // These stdlib scalar types have a C-side typedef prefixed
                // `Certo` (`CertoDateTime`, etc.) rather than matching their
                // bare Certo name — the same gap `ty_to_c.rs` (the
                // resolved-`Ty` version of this function) already fixed, but
                // this separate AST-level copy (used for `type X = { ... }`
                // record *field* declarations specifically) never got the
                // same fix, so a `DateTime`/`Date`/`Duration`-typed field
                // emitted the literal, undeclared C identifier `DateTime`
                // instead — confirmed via a real `certo db pull`-generated
                // struct with a `createdAt: DateTime` field failing to
                // compile (BACKLOG item 134, found while verifying the
                // struct-boxing fix end-to-end, not caused by it).
                // BACKLOG item 317 — `Timestamp` was missing from this list
                // (present in `ty_to_c.rs`'s own identical match, item 164,
                // ever since), so a record *field* typed `Timestamp`
                // (unlike a function param/return, which already went
                // through `ty_to_c.rs`) emitted the bare, undeclared C
                // identifier `Timestamp` — confirmed via a real struct
                // definition with a `dueAt: Timestamp` field failing to
                // compile. `Timestamp` has no separate runtime type of its
                // own (see `ty_to_c.rs`'s own doc comment) — reuses
                // `CertoDateTime` exactly, same as there.
                "DateTime" | "Date" | "Duration" | "Timezone" => format!("Certo{}", name),
                "Timestamp" => "CertoDateTime".to_string(),
                "JsonValue" | "ProcessResult" => format!("Certo{}*", name),
                other     => c_ident(other),
            }
        }
        // `T?` — matches the internal nullable-pointer Option representation
        // used everywhere else (`ty_to_c(Ty::Option(_)) => "void*"`), not the
        // separate ABI-stable `certo_option_t` struct crates/ffi's header
        // generator deliberately uses instead for its public-facing API.
        TypeExpr::Option { .. }  => "void*".into(),
        TypeExpr::Tuple { elements, .. } => {
            if elements.is_empty() { "int64_t".into() } else { "void*".into() }
        }
        TypeExpr::Fn { .. }      => "certo_fn_t".into(),
        TypeExpr::Record { .. }  => "void*".into(),
        TypeExpr::Ptr { inner, .. } => format!("{}*", ast_ty_to_c_str(&inner.node)),
        TypeExpr::Param { .. }   => "void*".into(),
        // Same runtime representation as bare `Decimal` — the parameter is a
        // compile-time-only refinement.
        TypeExpr::DecimalParam { .. } => "certo_decimal_t".into(),
        // Same runtime representation as bare `Text` — the max length is a
        // compile-time-only refinement (BACKLOG item 147).
        TypeExpr::BoundedTextParam { .. } => "certo_text_t".into(),
    }
}

/// A field's C type, aware of the enclosing `type`'s own declared type
/// parameters (`type Box<T> = { value: T }`'s `T`) — BACKLOG item 119. The
/// parser never actually constructs `TypeExpr::Param` (verified dead code),
/// so a bare type-param reference always parses as an ordinary
/// `TypeExpr::Named` with an empty-args, single-segment path; `ast_ty_to_c_str`
/// alone has no way to tell that apart from a real (and here, undeclared) type
/// name. Its C storage is `void*` regardless of what it's instantiated to,
/// matching how `crates/mir/src/lower.rs` heap-boxes/unboxes such fields.
/// `self_ref_name` is `Some(parent_type_name)` only when called for a
/// sum-type variant's own field — BACKLOG item 277: a *direct* self-
/// referential field (e.g. `Node(left: Tree, right: Tree)`, where `left`'s
/// declared type is `Tree`, `Node`'s own enclosing type) can't be embedded
/// inline-by-value the way an ordinary nested field is — that's an
/// infinite-size C struct — so it's stored as a pointer instead. The value
/// itself is never exposed as a raw pointer to Certo source: construction
/// heap-boxes it (MIR's call-site argument lowering) and pattern-matching
/// dereferences it back to a plain value (MIR's field-binding lowering).
fn field_c_ty(te: &certo_ast::types::TypeExpr, type_params: &[String], self_ref_name: Option<&str>) -> String {
    if let certo_ast::types::TypeExpr::Named { path, args, .. } = te {
        if args.is_empty() && path.segments.len() == 1 {
            if let Some(seg) = path.segments.first() {
                if type_params.iter().any(|p| p == &seg.node) {
                    return "void*".into();
                }
                if self_ref_name == Some(seg.node.as_str()) {
                    // `struct {name}*`, not the bare `{name}*` typedef alias
                    // — at this point in the generated C, we're still
                    // *inside* the `typedef struct {name} { ... } {name};`
                    // that declares this very type, so only its struct tag
                    // (added specifically for this case, see the `TypeBody::
                    // Sum` arm above) is a valid type name yet; the typedef
                    // alias itself isn't usable until that whole statement
                    // completes.
                    return format!("struct {}*", c_ident(&seg.node));
                }
            }
        }
    }
    ast_ty_to_c_str(te)
}

fn const_expr_to_c(expr: &certo_hir::HirExpr) -> String {
    use certo_hir::HirExprKind;
    match &expr.kind {
        HirExprKind::Int(n)     => n.to_string(),
        HirExprKind::Float(f)   => format!("{:.}", f),
        HirExprKind::Bool(b)    => if *b { "true".into() } else { "false".into() },
        HirExprKind::Str(s)     => {
            let escaped: String = s.chars().flat_map(|c| match c {
                '\n' => vec!['\\', 'n'],
                '\r' => vec!['\\', 'r'],
                '\t' => vec!['\\', 't'],
                '\\' => vec!['\\', '\\'],
                '"'  => vec!['\\', '"'],
                c    => vec![c],
            }).collect();
            format!("CERTO_STR(\"{}\")", escaped)
        }
        HirExprKind::Unit       => "CERTO_UNIT".into(),
        _                       => "/* expr */0".into(),
    }
}

fn const_expr_ty(expr: &certo_hir::HirExpr) -> String {
    use certo_hir::HirExprKind;
    match &expr.kind {
        HirExprKind::Int(_)   => "int64_t".into(),
        HirExprKind::Float(_) => "double".into(),
        HirExprKind::Bool(_)  => "bool".into(),
        HirExprKind::Str(_)   => "certo_text_t".into(),
        HirExprKind::Unit     => "int64_t".into(),
        _                     => "void*".into(),
    }
}

/// Attempt to convert a simple Certo AST expression to a C statement string.
/// Returns `None` for complex expressions that require HIR lowering.
fn simple_expr_to_c(expr: &certo_ast::expr::Expr) -> Option<String> {
    use certo_ast::expr::Expr;
    match expr {
        // fn_name(args...) where args are simple
        Expr::App { func, args, .. } => {
            let fname = match &func.node {
                Expr::Path { path, .. } => {
                    path.segments.iter()
                        .map(|s| s.node.as_str())
                        .collect::<Vec<_>>()
                        .join(".")
                }
                _ => return None,
            };
            let c_fn = c_fn_name(&fname);
            let c_args: Option<Vec<String>> = args.iter()
                .map(|a| simple_expr_to_c_rvalue(&a.value.node))
                .collect();
            Some(format!("{}({})", c_fn, c_args?.join(", ")))
        }
        _ => None,
    }
}

fn simple_expr_to_c_rvalue(expr: &certo_ast::expr::Expr) -> Option<String> {
    use certo_ast::expr::{Expr, Lit};
    match expr {
        Expr::Lit { value, .. } => match value {
            Lit::String(s) => {
                let e: String = s.chars().flat_map(|c| match c {
                    '\n' => vec!['\\', 'n'],
                    '\r' => vec!['\\', 'r'],
                    '\t' => vec!['\\', 't'],
                    '\\' => vec!['\\', '\\'],
                    '"'  => vec!['\\', '"'],
                    c    => vec![c],
                }).collect();
                Some(format!("CERTO_STR(\"{}\")", e))
            }
            Lit::Int(n)    => Some(n.to_string()),
            Lit::Float(f)  => Some(f.to_string()),
            Lit::Bool(b)   => Some(if *b { "true".into() } else { "false".into() }),
            _ => None,
        },
        Expr::Path { path, .. } => {
            if path.segments.len() == 1 {
                Some(path.segments[0].node.clone())
            } else {
                None
            }
        }
        _ => None,
    }
}

