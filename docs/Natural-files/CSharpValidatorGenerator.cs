    private static string BuildRuleViolationException() => """
        namespace RuleGenerator.Validators;

        /// <summary>
        /// Thrown when a business rule is violated.
        /// Generated by RuleGenerator — do not edit.
        /// </summary>
        public sealed class RuleViolationException : Exception
        {
            /// <summary>Machine-readable rule code e.g. ACCOUNT_NOT_VERIFIED</summary>
            public string RuleCode { get; }

            /// <summary>Human-readable message suitable for API responses</summary>
            public string UserMessage { get; }

            public RuleViolationException(string ruleCode, string userMessage)
                : base($"[{ruleCode}] {userMessage}")
            {
                RuleCode    = ruleCode;
                UserMessage = userMessage;
            }
        }

        /// <summary>
        /// Aggregates multiple rule violations rather than stopping at the first.
        /// Useful when validating a full form submission.
        /// </summary>
        public sealed class AggregateRuleViolationException : Exception
        {
            public IReadOnlyList<RuleViolationException> Violations { get; }

            public AggregateRuleViolationException(
                IEnumerable<RuleViolationException> violations)
                : base("One or more business rules were violated.")
            {
                Violations = violations.ToList();
            }
        }
        """;

    private static string BuildValidationContext(ResolvedDomain domain)
    {
        var sb = new StringBuilder();
        sb.AppendLine("namespace RuleGenerator.Validators;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Carries the entity and all related data needed to evaluate rules.");
        sb.AppendLine("/// Populate before calling a validator. Null references mean");
        sb.AppendLine("/// the related entity was not loaded — the validator will skip");
        sb.AppendLine("/// conditions that depend on missing context.");
        sb.AppendLine("/// Generated by RuleGenerator — do not edit.");
        sb.AppendLine("/// </summary>");

        // One context class per entity
        foreach (var entity in domain.Entities)
        {
            sb.AppendLine($"public sealed class {entity.Id}Context");
            sb.AppendLine("{");

            // The primary entity fields as a nested record
            sb.AppendLine($"    // Primary entity");
            foreach (var field in entity.Fields.Where(f => !f.PrimaryKey))
            {
                var csType = ResolveCSharpType(field);
                var nullable = !field.Required ? "?" : "";
                sb.AppendLine($"    public {csType}{nullable} {Capitalise(field.Name)} {{ get; init; }}");
            }

            // Related entity contexts (one property per reference field)
            var refs = entity.Fields.Where(f => f.Kind == FieldKind.Reference).ToList();
            if (refs.Any())
            {
                sb.AppendLine();
                sb.AppendLine($"    // Related entities");
                foreach (var refField in refs)
                {
                    var refEntity = refField.ReferencedEntity!.Id;
                    sb.AppendLine($"    public {refEntity}Context? {Capitalise(refField.Name)} {{ get; init; }}");
                }
            }

            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    private static string BuildIValidator() => """
        namespace RuleGenerator.Validators;

        /// <summary>
        /// Common interface for all generated validator classes.
        /// Generated by RuleGenerator — do not edit.
        /// </summary>
        public interface IValidator<TContext>
        {
            /// <summary>
            /// Validates all rules for this entity+trigger combination.
            /// Throws RuleViolationException on the first violation.
            /// </summary>
            void Validate(TContext context);

            /// <summary>
            /// Validates all rules and collects all violations rather than
            /// stopping at the first. Returns empty list if all rules pass.
            /// </summary>
            IReadOnlyList<RuleViolationException> ValidateAll(TContext context);
        }
        """;

    // =========================================================================
    // VALIDATOR CLASS
    // =========================================================================

    private string BuildValidatorClass(
        string entity,
        string trigger,
        List<RuleDefinition> rules,
        ResolvedDomain domain)
    {
        var className = $"{entity}{Capitalise(trigger)}Validator";
        var contextType = $"{entity}Context";

        var sb = new StringBuilder();

        // Header
        sb.AppendLine("using System.Text.RegularExpressions;");
        sb.AppendLine("namespace RuleGenerator.Validators;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Validates business rules for {entity}.{trigger}.");
        sb.AppendLine("/// <para>Rules enforced:</para>");
        sb.AppendLine("/// <list type=\"bullet\">");
        foreach (var rule in rules)
            sb.AppendLine($"///   <item>{rule.Id} — {rule.Description}</item>");
        sb.AppendLine("/// </list>");
        sb.AppendLine("/// Generated by RuleGenerator — do not edit.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public sealed class {className} : IValidator<{contextType}>");
        sb.AppendLine("{");

        // Order rules respecting depends_on and priority
        var ordered = OrderRules(rules);

        // Validate() — fail fast
        sb.AppendLine($"    /// <inheritdoc/>");
        sb.AppendLine($"    public void Validate({contextType} context)");
        sb.AppendLine("    {");
        WriteValidateBody(sb, ordered, domain, failFast: true);
        sb.AppendLine("    }");
        sb.AppendLine();

        // ValidateAll() — collect all violations
        sb.AppendLine($"    /// <inheritdoc/>");
        sb.AppendLine($"    public IReadOnlyList<RuleViolationException> ValidateAll({contextType} context)");
        sb.AppendLine("    {");
        sb.AppendLine("        var violations = new List<RuleViolationException>();");
        WriteValidateBody(sb, ordered, domain, failFast: false);
        sb.AppendLine("        return violations;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Private Check methods — one per rule
        foreach (var rule in ordered)
        {
            WriteCheckMethod(sb, rule, domain);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private void WriteValidateBody(
        StringBuilder sb,
        List<RuleDefinition> ordered,
        ResolvedDomain domain,
        bool failFast)
    {
        // Track which overrides rules are active so we can skip overridden rules
        var overrideMap = BuildOverrideMap(ordered);

        // Group: rules that override others vs rules that are overrideable
        foreach (var rule in ordered)
        {
            var indent = "        ";

            // If this rule is overridden by another, wrap in an override check
            if (overrideMap.TryGetValue(rule.Id, out var overridingRuleId))
            {
                var overridingRule = ordered.First(r => r.Id == overridingRuleId);
                sb.AppendLine($"{indent}// Rule '{rule.Id}' is suspended when '{overridingRuleId}' condition passes");
                sb.AppendLine($"{indent}if (!Check_{ToPascalId(overridingRuleId)}_Condition(context))");
                sb.AppendLine($"{indent}{{");
                WriteRuleCall(sb, rule, domain, failFast, indent + "    ");
                sb.AppendLine($"{indent}}}");
            }
            else if (rule.Overrides == null) // Not an override rule itself — emit normally
            {
                WriteRuleCall(sb, rule, domain, failFast, indent);
            }
            // Override rules themselves don't appear in the main sequence —
            // they are only referenced in the override check above
        }
    }

    private void WriteRuleCall(
        StringBuilder sb,
        RuleDefinition rule,
        ResolvedDomain domain,
        bool failFast,
        string indent)
    {
        // depends_on: only evaluate if prerequisite rules passed
        if (rule.DependsOn.Any())
        {
            var deps = string.Join(" && ",
                rule.DependsOn.Select(d => $"Check_{ToPascalId(d)}_Condition(context)"));
            sb.AppendLine($"{indent}// Depends on: {string.Join(", ", rule.DependsOn)}");
            sb.AppendLine($"{indent}if ({deps})");
            sb.AppendLine($"{indent}{{");
            WriteViolationCheck(sb, rule, failFast, indent + "    ");
            sb.AppendLine($"{indent}}}");
        }
        else
        {
            WriteViolationCheck(sb, rule, failFast, indent);
        }
    }

    private static void WriteViolationCheck(
        StringBuilder sb,
        RuleDefinition rule,
        bool failFast,
        string indent)
    {
        sb.AppendLine($"{indent}// {rule.Description}");
        sb.AppendLine($"{indent}if (!Check_{ToPascalId(rule.Id)}_Condition(context))");
        sb.AppendLine($"{indent}{{");

        if (failFast)
        {
            sb.AppendLine($"{indent}    throw new RuleViolationException(");
            sb.AppendLine($"{indent}        \"{rule.Error.Code}\",");
            sb.AppendLine($"{indent}        \"{EscapeString(rule.Error.Message)}\");");
        }
        else
        {
            sb.AppendLine($"{indent}    violations.Add(new RuleViolationException(");
            sb.AppendLine($"{indent}        \"{rule.Error.Code}\",");
            sb.AppendLine($"{indent}        \"{EscapeString(rule.Error.Message)}\"));");
        }

        sb.AppendLine($"{indent}}}");
    }

    // =========================================================================
    // CHECK METHODS
    // =========================================================================

    private void WriteCheckMethod(
        StringBuilder sb,
        RuleDefinition rule,
        ResolvedDomain domain)
    {
        var methodName = $"Check_{ToPascalId(rule.Id)}_Condition";
        sb.AppendLine($"    /// <summary>{EscapeString(rule.Description)}</summary>");
        sb.AppendLine($"    private static bool {methodName}({rule.Entity}Context context)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return {EmitCondition(rule.Condition, domain, "context", 2)};");
        sb.AppendLine("    }");
    }

    // =========================================================================
    // CONDITION EMISSION
    // =========================================================================

    private string EmitCondition(
        ConditionNode node,
        ResolvedDomain domain,
        string ctx,
        int depth)
    {
        var indent = new string(' ', depth * 4);
        var innerIndent = new string(' ', (depth + 1) * 4);

        // --- Composite nodes ---
        if (node.All != null)
            return EmitComposite(node.All, "&&", domain, ctx, depth);

        if (node.Any != null)
            return EmitComposite(node.Any, "||", domain, ctx, depth);

        if (node.None != null)
        {
            var inner = EmitComposite(node.None, "||", domain, ctx, depth);
            return $"!({inner})";
        }

        // --- Named constraint reference — inline the condition ---
        if (node.IsConstraintRef)
        {
            var constraint = domain.Types
                .Select(_ => (ConditionNode?)null)
                .FirstOrDefault(); // placeholder — resolved below

            // Look up the constraint condition from the raw rules
            // (constraints are carried through as ConditionNodes in the domain)
            // For now emit a comment placeholder — the resolver would inline this
            return $"true /* constraint: {node.Constraint} — inlined at resolve time */";
        }

        // --- Named temporal reference ---
        if (node.IsTemporalRef)
        {
            return EmitTemporalCondition(node, ctx);
        }

        // --- Field comparison ---
        if (node.IsFieldComparison)
        {
            return EmitFieldComparison(node, ctx);
        }

        return "true /* unresolved condition */";
    }

    private string EmitComposite(
        List<ConditionNode> children,
        string op,
        ResolvedDomain domain,
        string ctx,
        int depth)
    {
        if (!children.Any()) return "true";
        if (children.Count == 1) return EmitCondition(children[0], domain, ctx, depth);

        var parts = children
            .Select(c => $"({EmitCondition(c, domain, ctx, depth + 1)})")
            .ToList();

        return string.Join($"\n            {op} ", parts);
    }

    private static string EmitFieldComparison(ConditionNode node, string ctx)
    {
        var field = DotPathToCSharp(node.Field!, ctx);
        var op = node.Operator!;
        var value = node.Value;

        // Check if value is a field reference (dot notation) or a literal
        var isFieldRef = value is string s && s.Contains('.');
        var rhs = isFieldRef
            ? DotPathToCSharp(value!.ToString()!, ctx)
            : FormatLiteral(value);

        return op switch
        {
            "eq"         => $"{field} == {rhs}",
            "not_eq"     => $"{field} != {rhs}",
            "gt"         => $"{field} > {rhs}",
            "gte"        => $"{field} >= {rhs}",
            "lt"         => $"{field} < {rhs}",
            "lte"        => $"{field} <= {rhs}",
            "in"         => EmitInExpression(field, value, negate: false),
            "not_in"     => EmitInExpression(field, value, negate: true),
            "exists"     => $"{field} != null",
            "not_exists" => $"{field} == null",
            "matches"    => $"Regex.IsMatch({field} ?? string.Empty, @\"{value}\")",
            "not_matches"=> $"!Regex.IsMatch({field} ?? string.Empty, @\"{value}\")",
            "contains"   => $"({field} ?? string.Empty).Contains({rhs})",
            "starts_with"=> $"({field} ?? string.Empty).StartsWith({rhs})",
            _            => $"true /* unknown operator: {op} */"
        };
    }

    private static string EmitTemporalCondition(ConditionNode node, string ctx)
    {
        // temporal references encode a named time window with operator
        // e.g. temporal: standard_void_window, field: createdAt, operator: age_lt
        // We emit DateTimeOffset arithmetic directly
        var fieldPath = DotPathToCSharp(node.Field!, ctx);
        var op = node.Operator ?? "age_lt";

        // The temporal duration/unit are carried on the node via the YAML
        // In the resolved domain we would have inlined these — for now we
        // emit a clearly labelled expression with a TODO for the resolver to fill
        // In practice the resolver inlines the duration/unit before generation
        var comparison = op switch
        {
            "age_lt"  => $"(DateTimeOffset.UtcNow - {fieldPath}).TotalDays < /* {node.Temporal}.days */",
            "age_gt"  => $"(DateTimeOffset.UtcNow - {fieldPath}).TotalDays > /* {node.Temporal}.days */",
            "age_lte" => $"(DateTimeOffset.UtcNow - {fieldPath}).TotalDays <= /* {node.Temporal}.days */",
            "age_gte" => $"(DateTimeOffset.UtcNow - {fieldPath}).TotalDays >= /* {node.Temporal}.days */",
            _         => $"true /* unknown temporal operator: {op} */"
        };

        return comparison;
    }

    private static string EmitInExpression(string field, object? value, bool negate)
    {
        // value is expected to be a list
        string listLiteral;
        if (value is List<object> items)
            listLiteral = string.Join(", ", items.Select(FormatLiteral));
        else
            listLiteral = FormatLiteral(value);

        var expr = $"new[] {{ {listLiteral} }}.Contains({field})";
        return negate ? $"!{expr}" : expr;
    }

