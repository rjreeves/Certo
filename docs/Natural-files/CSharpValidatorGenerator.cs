    // UTILITIES
    // =========================================================================

    private static Dictionary<string, string> BuildOverrideMap(List<RuleDefinition> rules)
    {
        // overrideMap[overridden_rule_id] = overriding_rule_id
        var map = new Dictionary<string, string>();
        foreach (var rule in rules.Where(r => r.Overrides != null))
            map[rule.Overrides!] = rule.Id;
        return map;
    }

    private static List<RuleDefinition> OrderRules(List<RuleDefinition> rules)
    {
        // Sort: higher priority first, then depends_on ordering
        var sorted = rules
            .OrderByDescending(r => r.Priority)
            .ToList();

        // Topological sort on depends_on
        var result = new List<RuleDefinition>();
        var visited = new HashSet<string>();
        var ruleById = sorted.ToDictionary(r => r.Id);

        void Visit(RuleDefinition rule)
        {
            if (visited.Contains(rule.Id)) return;
            foreach (var dep in rule.DependsOn)
                if (ruleById.TryGetValue(dep, out var depRule))
                    Visit(depRule);
            visited.Add(rule.Id);
            result.Add(rule);
        }

        foreach (var rule in sorted)
            Visit(rule);

        return result;
    }

    /// <summary>
    /// Converts a dot-notation field path to a C# null-safe property chain.
    /// "user.verified"  → "context.User?.Verified"
    /// "order.total"    → "context.Total"   (same entity)
    /// </summary>
    private static string DotPathToCSharp(string path, string ctx)
    {
        var parts = path.Split('.');
        if (parts.Length == 1)
            return $"{ctx}.{Capitalise(parts[0])}";

        // First segment is the relation name, rest is field path
        var chain = new StringBuilder(ctx);
        for (int i = 0; i < parts.Length; i++)
        {
            var isLast = i == parts.Length - 1;
            chain.Append(isLast ? $".{Capitalise(parts[i])}" : $".{Capitalise(parts[i])}?");
        }
        return chain.ToString();
    }

    private static string ResolveCSharpType(ResolvedField field)
    {
        return field.Kind switch
        {
            FieldKind.Enum      => field.EnumType!.PascalName,
            FieldKind.Reference => "Guid",   // FK stored as Guid
            FieldKind.Scalar    => CSharpTypeMap.GetValueOrDefault(
                                        field.PrimitiveType ?? "text", "string"),
            _ => "object"
        };
    }

    private static string FormatLiteral(object? value)
    {
        return value switch
        {
            null          => "null",
            bool b        => b ? "true" : "false",
            int i         => i.ToString(),
            long l        => l.ToString(),
            double d      => d.ToString("G"),
            decimal dec   => $"{dec}m",
            string s      => $"\"{EscapeString(s)}\"",
            _             => $"\"{EscapeString(value.ToString() ?? "")}\""
        };
    }

    private static string EscapeString(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string ToPascalId(string ruleId) =>
        string.Concat(ruleId.Split('_').Select(Capitalise));

    private static string Capitalise(string s) =>
        string.IsNullOrEmpty(s) ? s : char.ToUpper(s[0]) + s[1..];

    private static Dictionary<(string, string), List<RuleDefinition>>
        GroupRulesByEntityAndTrigger(List<RuleDefinition> rules) =>
        rules
            .GroupBy(r => (r.Entity, r.Trigger))
            .ToDictionary(g => g.Key, g => g.ToList());

    private static async Task WriteFile(string dir, string filename, string content)
    {
        await File.WriteAllTextAsync(Path.Combine(dir, filename), content);
    }
}
