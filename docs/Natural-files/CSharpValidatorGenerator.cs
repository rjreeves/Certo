using System.Text;
using RuleGenerator.Models;

namespace RuleGenerator.Generators;

/// <summary>
/// Generates C# validator classes from business rule definitions.
///
/// Output structure:
///   Validators/
///     RuleViolationException.cs     — exception thrown on rule violation
///     ValidationContext.cs          — carries entity + related data into validators
///     IValidator.cs                 — common validator interface
///     {Entity}Validators/
///       {Entity}{Trigger}Validator.cs  — one class per entity+trigger group
///     ValidatorRegistry.cs          — registers and runs all validators by trigger
///
/// Design principles:
///   - One validator class per entity+trigger combination
///   - Each rule becomes one private Check method
///   - Rules with depends_on chain via early-exit ordering
///   - Rules with overrides suppress the overridden rule when their condition passes
///   - Composite conditions (all/any/none) emit nested if expressions
///   - Named constraints are inlined at code generation time (no runtime lookup)
///   - Temporal conditions use DateTimeOffset arithmetic
///   - Generated code has no runtime dependency on the generator
/// </summary>
public class CSharpValidatorGenerator : IGenerator
{
    public string Name => "csharp";

    // Maps our primitive type names to C# types
    private static readonly Dictionary<string, string> CSharpTypeMap = new()
    {
        ["text"]      = "string",
        ["integer"]   = "int",
        ["boolean"]   = "bool",
        ["uuid"]      = "Guid",
        ["decimal"]   = "decimal",
        ["timestamp"] = "DateTimeOffset",
        ["date"]      = "DateOnly",
        ["time"]      = "TimeOnly",
        ["jsonb"]     = "object",
        ["bytea"]     = "byte[]"
    };

    private static readonly Dictionary<string, string> TemporalUnitMap = new()
    {
        ["minutes"] = "Minutes",
        ["hours"]   = "Hours",
        ["days"]    = "Days",
        ["weeks"]   = "Days",   // weeks expressed as days * 7
        ["months"]  = "Days",   // months expressed approximately
        ["years"]   = "Days"
    };

    public async Task GenerateAsync(ResolvedDomain domain, string outputPath)
    {
        var validatorsPath = Path.Combine(outputPath, "Validators");
        Directory.CreateDirectory(validatorsPath);

        // 1. Shared infrastructure files
        await WriteFile(validatorsPath, "RuleViolationException.cs",
            BuildRuleViolationException());
        await WriteFile(validatorsPath, "ValidationContext.cs",
            BuildValidationContext(domain));
        await WriteFile(validatorsPath, "IValidator.cs",
            BuildIValidator());

        // 2. One validator class per entity+trigger group
        var groups = GroupRulesByEntityAndTrigger(domain.Rules);
        var registrations = new List<(string entity, string trigger, string className)>();

        foreach (var ((entity, trigger), rules) in groups)
        {
            var entityDir = Path.Combine(validatorsPath, $"{entity}Validators");
            Directory.CreateDirectory(entityDir);

            var className = $"{entity}{Capitalise(trigger)}Validator";
            var content = BuildValidatorClass(entity, trigger, rules, domain);
            await WriteFile(entityDir, $"{className}.cs", content);

            registrations.Add((entity, trigger, className));
            Console.WriteLine($"[csharp] Validators/{entity}Validators/{className}.cs");
        }

        // 3. Registry
        await WriteFile(validatorsPath, "ValidatorRegistry.cs",
            BuildValidatorRegistry(registrations));

        Console.WriteLine($"[csharp] Validators/RuleViolationException.cs");
        Console.WriteLine($"[csharp] Validators/ValidationContext.cs");
        Console.WriteLine($"[csharp] Validators/IValidator.cs");
        Console.WriteLine($"[csharp] Validators/ValidatorRegistry.cs");
    }

