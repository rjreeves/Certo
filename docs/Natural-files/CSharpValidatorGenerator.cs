    private static string BuildValidatorRegistry(
        List<(string entity, string trigger, string className)> registrations)
    {
        var sb = new StringBuilder();
        sb.AppendLine("namespace RuleGenerator.Validators;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Central registry for all generated validators.");
        sb.AppendLine("/// Resolve and call validators by entity name and trigger.");
        sb.AppendLine("/// Register with your DI container via AddRuleValidators().");
        sb.AppendLine("/// Generated by RuleGenerator — do not edit.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class ValidatorRegistry");
        sb.AppendLine("{");

        // Group by entity for cleaner access pattern
        var byEntity = registrations
            .GroupBy(r => r.entity)
            .OrderBy(g => g.Key);

        foreach (var entityGroup in byEntity)
        {
            var entity = entityGroup.Key;
            sb.AppendLine($"    // {entity}");
            foreach (var (_, trigger, className) in entityGroup)
            {
                sb.AppendLine($"    public static readonly {className} " +
                              $"{entity}{Capitalise(trigger)} = new();");
            }
            sb.AppendLine();
        }

        // Validate method for runtime dispatch by string trigger
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Validate by entity type and trigger name at runtime.");
        sb.AppendLine("    /// Throws RuleViolationException on the first violation.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static void Validate<TContext>(");
        sb.AppendLine("        string entity, string trigger, TContext context)");
        sb.AppendLine("        where TContext : class");
        sb.AppendLine("    {");
        sb.AppendLine("        var key = $\"{entity}.{trigger}\";");
        sb.AppendLine("        switch (key)");
        sb.AppendLine("        {");

        foreach (var (entity, trigger, className) in registrations)
        {
            sb.AppendLine($"            case \"{entity}.{trigger}\":");
            sb.AppendLine($"                if (context is {entity}Context {entity.ToLower()}Ctx)");
            sb.AppendLine($"                    {entity}{Capitalise(trigger)}.Validate({entity.ToLower()}Ctx);");
            sb.AppendLine($"                break;");
        }

        sb.AppendLine("            default:");
        sb.AppendLine("                throw new ArgumentException(");
        sb.AppendLine("                    $\"No validator registered for '{entity}.{trigger}'\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // Extension method for DI registration
        sb.AppendLine("/// <summary>Extension methods for registering validators with DI.</summary>");
        sb.AppendLine("public static class ValidatorServiceExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    public static IServiceCollection AddRuleValidators(");
        sb.AppendLine("        this IServiceCollection services)");
        sb.AppendLine("    {");
        foreach (var (entity, trigger, className) in registrations)
            sb.AppendLine($"        services.AddSingleton<{className}>();");
        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

